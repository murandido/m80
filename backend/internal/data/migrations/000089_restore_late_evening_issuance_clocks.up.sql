-- Gives back the real clock to the 250 issuances the panel stamped at 12:00.
--
-- Until #85, rebaseToDay swapped the clock of an issuance recorded between 21:00 and 23:59
-- (Sao Paulo) for midday, so these rows sorted ahead of everything recorded that afternoon
-- on the board and on the payments screen. Their sale was inserted in the same request and
-- kept the real moment, so that is the clock restored here. A read-only survey on 15/11/2026
-- found exactly these rows (one sale each, created on the same Sao Paulo day after 21:00);
-- the owner approved correcting them.
--
-- The calendar day does not change, so no inventory period is crossed. Within an open
-- period the costing breaks same-day ties by created_at and will recompute in the corrected
-- order; closed periods are frozen and stay as they are.
--
-- The ids are listed so nothing outside the survey is touched, and each row must still be
-- at exactly 12:00 local - a row corrected by hand since then is left alone.
