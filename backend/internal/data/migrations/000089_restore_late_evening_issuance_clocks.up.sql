SET created_at = sales.created_at
FROM sales
WHERE sales.issuance_id = issuances.id
  AND (issuances.created_at AT TIME ZONE 'America/Sao_Paulo')::time = '12:00:00'
  AND (sales.created_at AT TIME ZONE 'America/Sao_Paulo')::date = (issuances.created_at AT TIME ZONE 'America/Sao_Paulo')::date
