-- Re-dates the 85 payments the "Pago" switch filed a day late.
--
-- Until #30 (in production since 03/11/2026) the switch wrote paid_on from time.Now() in a
-- container running in UTC, so a click between 21:00 and 23:59 in Sao Paulo was dated the
-- next day. 17 of these were clicked on 31/10 and landed in November's figures. A read-only
-- survey on 15/11/2026 found exactly these rows and none after the fix; the owner approved
-- correcting all 85 (court review D2).
--
-- The ids are listed rather than re-derived so the migration touches the surveyed rows and
-- nothing else, and so the down file can undo exactly this change. Each row also has to still
-- be one day ahead of its Sao Paulo click day - a row someone has since corrected by hand, or
-- one that does not exist (the ca-mode database), is left alone.
UPDATE sale_payments
SET paid_on = (created_at AT TIME ZONE 'America/Sao_Paulo')::date
WHERE note = 'Baixa pelo interruptor de pago'
  AND paid_on = (created_at AT TIME ZONE 'America/Sao_Paulo')::date + 1
